const dict: Record<Lang, Record<Key, string>> = { en, fr };

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const s = dict[state.settings.lang][key] ?? en[key];
  return s.replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? ''));
}

export const tAny = (key: string, params?: Record<string, string | number>) => t(key as Key, params);

/** Short duration, e.g. "10 min", "3 days", "2 mo". */
export function formatInterval(ms: number): string {
  const m = ms / 60000;
  if (m < 1) return t('now');
  if (m < 60) return t('min', { n: Math.round(m) });
  const h = m / 60;
  if (h < 24) return t('hour', { n: Math.round(h) });
  const d = Math.round(h / 24);
  if (d < 31) return t(d === 1 ? 'day' : 'days', { n: d });
  if (d < 365) return t('month', { n: Math.round(d / 30) });
  return t('year', { n: Math.round((d / 365) * 10) / 10 });
}
